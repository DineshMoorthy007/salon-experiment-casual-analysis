    # Non-completed appointments generate 0 revenue (or small late fee for 2% cancellations)
    for i in range(n_appointments):
        if raw_statuses[i] == "No-Show":
            raw_revenues[i] = 0.0
        elif raw_statuses[i] == "Cancelled":
            # 2% paid nominal cancellation charge of 150 INR
            raw_revenues[i] = 150.0 if np.random.rand() < 0.02 else 0.0

    # Injected Real-World Complication 3: A tiny percentage of data anomalies (negative values, extreme outliers)
    anomaly_indices = np.random.choice(n_appointments, size=45, replace=False)
    for idx in anomaly_indices[:20]:
        raw_revenues[idx] = -abs(raw_revenues[idx])  # negative refund glitch
    for idx in anomaly_indices[20:]:
        raw_revenues[idx] = raw_revenues[idx] * 25.0  # extra zero typo

    # Treatment group indicator (for retrospective / prospective experiment alignment)
    # Customers participating in 2024 trial
    trial_start = datetime(2024, 7, 1)
    treatment_group = []
    for i in range(n_appointments):
        d = chosen_dates[i]
        c = final_customers[i]
        if pd.isna(c) or d < trial_start:
            treatment_group.append("Non-Experiment")
        else:
            # Deterministic hash assignment based on customer id
            h = hash(c) % 2
            treatment_group.append("Treatment" if h == 1 else "Control")

    # Injected Real-World Complication 4: Missing booking channel in 1.2% records
    raw_channels = list(booking_channels)
    missing_ch_idx = np.random.choice(n_appointments, size=int(n_appointments * 0.012), replace=False)
    for idx in missing_ch_idx:
        raw_channels[idx] = np.nan

    appointment_ids = [f"APT{i+1:06d}" for i in range(n_appointments)]

    df_appointments = pd.DataFrame({
        "appointment_id": appointment_ids,
        "customer_id": final_customers,
        "outlet_id": chosen_outlets,
        "stylist_id": chosen_stylists,
        "service_id": chosen_services,
        "raw_service_name": raw_service_names,
        "appointment_date": [d.strftime("%Y-%m-%d") for d in chosen_dates],
        "appointment_time": appointment_times,
        "booking_channel": raw_channels,
        "appointment_status": raw_statuses,
        "cancellation_indicator": cancellation_ind,
        "no_show_indicator": no_show_ind,
        "walk_in_indicator": walk_in_ind,
        "treatment_group": treatment_group,
        "revenue": raw_revenues,
        "_internal_true_no_show": (chosen_statuses == "No-Show").astype(int)  # Used for realistic cleaning audit
    })

    # Injected Real-World Complication 5: Duplicate records (~1.3% duplicates = ~3,900 rows)
    n_duplicates = int(n_appointments * 0.013)
    dup_indices = np.random.choice(n_appointments, size=n_duplicates, replace=False)
    df_duplicates = df_appointments.iloc[dup_indices].copy()
    # Concat and shuffle slightly
    df_appointments_raw = pd.concat([df_appointments, df_duplicates], ignore_index=True)
    df_appointments_raw = df_appointments_raw.sample(frac=1.0, random_state=RANDOM_SEED).reset_index(drop=True)

    print(f"Total appointments generated (with duplicates): {len(df_appointments_raw):,}")
    return df_appointments_raw


