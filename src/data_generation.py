def generate_stylists(df_outlets: pd.DataFrame) -> pd.DataFrame:
    """
    Generates ~125 professional stylists distributed across the 22 outlets.
    """
    levels = ["Junior", "Mid-Level", "Senior", "Master Stylist"]
    level_weights = [0.25, 0.40, 0.25, 0.10]
    specs = ["Hair Stylist", "Colorist & Stylist", "Skin Specialist", "Aesthetician", "Massage Therapist", "Bridal & Makeup Artist"]

    stylists = []
    stylist_idx = 1
    for _, outlet in df_outlets.iterrows():
        # 5 to 7 stylists per outlet based on tier
        if "Flagship" in outlet["tier"]:
            n_stylists = 7
        elif "High Volume" in outlet["tier"] or "Hub" in outlet["tier"]:
            n_stylists = 6
        else:
            n_stylists = 5

        for _ in range(n_stylists):
            s_id = f"STY{stylist_idx:03d}"
            lvl = np.random.choice(levels, p=level_weights)
            spec = np.random.choice(specs)
            stylists.append({
                "stylist_id": s_id,
                "outlet_id": outlet["outlet_id"],
                "experience_level": lvl,
                "specialization": spec,
                "base_retention_score": round(np.random.uniform(0.65, 0.95), 3)
            })
            stylist_idx += 1

    return pd.DataFrame(stylists)


def generate_customers(n_customers: int = 42000, df_outlets: pd.DataFrame = None) -> pd.DataFrame:
    """
    Generates customer profiles across demographic, behavioral, and regional segments.
    """
    customer_ids = [f"CUST{i+1:05d}" for i in range(n_customers)]
    
    # Age distribution: Bimodal/Gamma-like realistic distribution (18 to 72, peak at 28-34)
    ages = np.random.gamma(shape=9.0, scale=3.3, size=n_customers).astype(int) + 5
    ages = np.clip(ages, 18, 72)

    # Gender distribution (60% Female, 37% Male, 3% Non-Binary/Other)
    genders = np.random.choice(["Female", "Male", "Other"], size=n_customers, p=[0.60, 0.37, 0.03])

    # Segments
    segments = np.random.choice(["Budget", "Regular", "Premium", "VIP"], size=n_customers, p=[0.25, 0.45, 0.22, 0.08])

    # Acquisition channels
    channels = np.random.choice(
        ["Instagram", "Google Search", "Walk-in Referral", "Word of Mouth", "Festive Campaign", "Influencer Collab"],
        size=n_customers,
        p=[0.32, 0.24, 0.18, 0.14, 0.08, 0.04]
    )

    # Registration dates (2019-01-01 to 2024-06-30)
    start_dt = datetime(2019, 1, 1)
    end_dt = datetime(2024, 6, 30)
    total_days = (end_dt - start_dt).days
    random_days = np.random.randint(0, total_days, size=n_customers)
    reg_dates = [start_dt + timedelta(days=int(d)) for d in random_days]

    # Preferred outlet
    outlet_ids = df_outlets["outlet_id"].values
    preferred_outlets = np.random.choice(outlet_ids, size=n_customers)

    df_customers = pd.DataFrame({
        "customer_id": customer_ids,
        "age": ages,
        "gender": genders,
        "registration_date": [d.strftime("%Y-%m-%d") for d in reg_dates],
        "customer_segment": segments,
        "acquisition_source": channels,
        "preferred_outlet_id": preferred_outlets
    })
    return df_customers


