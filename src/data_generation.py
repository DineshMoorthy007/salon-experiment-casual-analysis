def generate_experiment_data(
    n_participants: int = 18000,
    df_customers: pd.DataFrame = None,
    df_outlets: pd.DataFrame = None
) -> pd.DataFrame:
    """
    Generates a prospective randomized A/B experiment dataset.
    Stratification: By outlet across active customers.
    Intervention: 'Intelligent WhatsApp Confirmation & Smart Rescheduling System'
    Targeting retention increase and no-show reduction.
    """
    print(f"Generating prospective randomized A/B experiment dataset ({n_participants} customers)...")
    
    # Select active customers
    all_cust_ids = df_customers["customer_id"].values
    selected_custs = np.random.choice(all_cust_ids, size=n_participants, replace=False)
    
    outlet_ids = df_outlets["outlet_id"].values
    
    experiment_records = []
    exp_start_date = "2024-07-01"

    # Stratified randomization by outlet
    for i, c_id in enumerate(selected_custs):
        outlet = outlet_ids[i % len(outlet_ids)]
        # Stratified coin toss within outlet: 50% Treatment, 50% Control
        assignment = "Treatment" if (i % 2 == 0) else "Control"

        # Baseline Pre-experiment metrics (past 6 months)
        pre_visits = int(np.random.negative_binomial(n=3, p=0.45) + 1)
        pre_avg_spend = np.random.normal(loc=1250, scale=320)
        pre_avg_spend = max(350.0, round(pre_avg_spend, 2))
        pre_revenue = round(pre_visits * pre_avg_spend, 2)
        
        # Previous no-shows (Poisson distribution)
        pre_no_shows = int(np.random.poisson(lam=0.45))

        # Baseline retention probability (Control ~ 57.5%)
        # Covariates impact: higher past visits increase retention, past no-shows decrease it
        latent_retention = 0.52 + (0.04 * min(pre_visits, 5)) - (0.08 * min(pre_no_shows, 3))
        
        # Baseline no-show probability (Control ~ 13.2%)
        latent_noshow = 0.11 + (0.05 * min(pre_no_shows, 3)) - (0.01 * min(pre_visits, 5))

        # True Causal Treatment Effect:
        # Treatment boosts retention by +6.2 percentage points and reduces no-show by -4.6 percentage points
        if assignment == "Treatment":
            retention_prob = np.clip(latent_retention + 0.062, 0.05, 0.95)
            noshow_prob = np.clip(latent_noshow - 0.046, 0.02, 0.90)
            spend_lift = np.random.normal(loc=110.0, scale=45.0)  # Upsell lift
        else:
            retention_prob = np.clip(latent_retention, 0.05, 0.95)
            noshow_prob = np.clip(latent_noshow, 0.02, 0.90)
            spend_lift = 0.0

        retention_outcome = int(np.random.rand() < retention_prob)
        no_show_outcome = int(np.random.rand() < noshow_prob)
        
        post_revenue_per_visit = round(max(300.0, pre_avg_spend + spend_lift + np.random.normal(0, 80)), 2)
        if retention_outcome == 0:
            # If customer didn't return, post revenue per visit is 0 or NaN; we record 0.0
            post_revenue_per_visit = 0.0

        experiment_records.append({
            "customer_id": c_id,
            "treatment_assignment": assignment,
            "outlet_id": outlet,
            "pre_experiment_visit_count": pre_visits,
            "pre_experiment_revenue": pre_revenue,
            "previous_no_show_history": pre_no_shows,
            "experiment_start_date": exp_start_date,
            "retention_outcome": retention_outcome,
            "revenue_per_visit": post_revenue_per_visit,
            "no_show_outcome": no_show_outcome
        })

    df_experiment = pd.DataFrame(experiment_records)
    return df_experiment


def generate_historical_regional_data() -> pd.DataFrame:
    """
    Generates historical monthly regional panel data for Difference-in-Differences (DiD) analysis.
    Covers 48 months (2021-01 to 2024-12) across 5 regions.
    Intervention: Month 25 (2023-01) policy change in Treatment regions (Central & North).
    """
    print("Generating historical regional panel data for Difference-in-Differences (DiD)...")
    regions = ["Central", "North", "East", "South", "West"]
    
    # 48 months from 2021-01 to 2024-12
    dates = pd.date_range(start="2021-01-01", periods=48, freq="MS")
    
    records = []
    
    # Regional baseline differences
    regional_baseline = {
        "Central": {"base_rev": 1420.0, "base_ret": 0.62, "base_noshow": 0.09, "base_apts": 6800},
        "North": {"base_rev": 1280.0, "base_ret": 0.58, "base_noshow": 0.105, "base_apts": 5400},
        "East": {"base_rev": 1150.0, "base_ret": 0.55, "base_noshow": 0.12, "base_apts": 5900},
        "South": {"base_rev": 1080.0, "base_ret": 0.54, "base_noshow": 0.125, "base_apts": 4600},
        "West": {"base_rev": 1120.0, "base_ret": 0.56, "base_noshow": 0.115, "base_apts": 3800},
    }

    # Treatment regions for policy intervention: Central & North
    treatment_regions = ["Central", "North"]
    intervention_start = pd.Timestamp("2023-01-01")

    for dt in dates:
        month_str = dt.strftime("%Y-%m")
        m = dt.month
        month_idx = (dt.year - 2021) * 12 + dt.month

        # Seasonality
        if m in [10, 11]:  # Diwali
            season_rev = 220.0
            season_ret = 0.05
            season_noshow = -0.015
            season_apts = 1.35
        elif m == 1:  # Pongal
            season_rev = 160.0
            season_ret = 0.04
            season_noshow = -0.010
            season_apts = 1.25
        elif m in [5, 6]:  # Wedding season
            season_rev = 140.0
            season_ret = 0.03
            season_noshow = -0.008
            season_apts = 1.20
        elif m in [7, 8]:  # Monsoon
            season_rev = -90.0
            season_ret = -0.03
            season_noshow = 0.020
            season_apts = 0.85
        else:
            season_rev = 0.0
            season_ret = 0.0
            season_noshow = 0.0
            season_apts = 1.0

        # General macro growth trend across all regions
        macro_growth_rev = month_idx * 6.5
        macro_growth_apts = 1.0 + (month_idx * 0.007)

        post_ind = 1 if dt >= intervention_start else 0

        for r in regions:
            is_treatment_region = 1 if r in treatment_regions else 0
            base = regional_baseline[r]

            # True DiD causal effect:
            # Treatment region in Post period experiences:
            # +185 INR revenue per visit, +4.5% retention, -3.2% no-show rate
            did_effect_rev = 185.0 if (is_treatment_region == 1 and post_ind == 1) else 0.0
            did_effect_ret = 0.045 if (is_treatment_region == 1 and post_ind == 1) else 0.0
            did_effect_noshow = -0.032 if (is_treatment_region == 1 and post_ind == 1) else 0.0

            # Realistic random noise
            noise_rev = np.random.normal(0, 25.0)
            noise_ret = np.random.normal(0, 0.012)
            noise_noshow = np.random.normal(0, 0.006)
            noise_apts = np.random.normal(0, 120)

            rev_per_visit = round(base["base_rev"] + season_rev + macro_growth_rev + did_effect_rev + noise_rev, 2)
            retention = round(np.clip(base["base_ret"] + season_ret + did_effect_ret + noise_ret, 0.30, 0.90), 4)
            noshow_rate = round(np.clip(base["base_noshow"] + season_noshow + did_effect_noshow + noise_noshow, 0.02, 0.30), 4)
            n_apts = int(max(500, round((base["base_apts"] * season_apts * macro_growth_apts) + (did_effect_rev * 1.5) + noise_apts)))

            records.append({
                "month": month_str,
                "region": r,
                "treatment_region_indicator": is_treatment_region,
                "post_intervention_indicator": post_ind,
                "revenue_per_visit": rev_per_visit,
                "customer_retention": retention,
                "no_show_rate": noshow_rate,
                "number_of_appointments": n_apts
            })

    df_historical = pd.DataFrame(records)
    return df_historical


